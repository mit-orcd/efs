#!/usr/bin/env python3
"""Wrap local graphify hooks; preserve original hooks and unrelated checkouts."""
from pathlib import Path
import os
import subprocess

root = Path(__file__).resolve().parents[1]
common = Path(subprocess.check_output(['git', 'rev-parse', '--git-common-dir'], cwd=root).decode().strip())
if not common.is_absolute():
    common = (root / common).resolve()
hooks = common / 'hooks'
if subprocess.run(['git', 'config', '--get', 'core.hooksPath'], cwd=root, stdout=subprocess.DEVNULL).returncode == 0:
    raise SystemExit('Custom core.hooksPath present; refusing to replace it')
for name in ('post-commit', 'post-merge', 'post-checkout', 'post-rewrite'):
    hook = hooks / name
    backup = hooks / (name + '.before-efs-code-graph')
    if hook.exists() and 'efs-code-graph-wrapper' in hook.read_text():
        continue
    if backup.exists():
        raise SystemExit(f'Backup already exists; inspect before installing: {backup}')
    if hook.exists():
        hook.rename(backup)
    hook.write_text('''#!/bin/sh
# efs-code-graph-wrapper: generated by scripts/install-code-graph-hooks.py
saved="$0.before-efs-code-graph"
top=$(git rev-parse --show-toplevel 2>/dev/null) || exit 0
local_git=$(git rev-parse --absolute-git-dir)
common_git=$(cd "$(git rev-parse --git-common-dir)" && pwd)
if [ "${GRAPHIFY_SKIP_HOOK:-0}" != 1 ] && [ "$local_git" = "$common_git" ] && [ -f "$top/tools/graphify/scope.json" ]; then
    # Retain unrelated hook actions, suppress only the old generic rebuild.
    if [ -x "$saved" ]; then GRAPHIFY_SKIP_HOOK=1 "$saved" "$@" || exit $?; fi
    exec sh "$top/scripts/rebuild-code-graph.sh"
fi
# Original hooks keep their own skip/linked-worktree/other-branch rules.
if [ -x "$saved" ]; then exec "$saved" "$@"; fi
''')
    hook.chmod(0o755)
print('Installed canonical graph wrappers; original hooks retained as *.before-efs-code-graph')
