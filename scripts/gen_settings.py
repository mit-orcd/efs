#!/usr/bin/env python3
"""W171 2c: generate the effective-settings table from the settings inventory.

Source: docs/how-it-works/settings.md. Its inventory rows (via
env_inventory.inventory_kinds) give each setting's kind; its "Effective-
settings listing" table gives default and role. Output:

  src/common/settings.c    the R(...) rows between the BEGIN/END GENERATED markers
  include/efs/settings.h   EFS_SETTINGS_OBSERVABILITY / EFS_SETTINGS_FAULT_HOOKS

  gen_settings.py [--root DIR]           rewrite both files
  gen_settings.py [--root DIR] --check   exit 1 with a diff when either is stale
                                         (the make test gate)
"""
import difflib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'scripts'))
import env_inventory  # noqa: E402

DOC = 'docs/how-it-works/settings.md'
LISTED = {'deployment input': 'DEP', 'numeric tunable': 'NUM'}
ROLES = {'daemon': 'D', 'client': 'C', 'both': 'B'}
COUNTS = (('EFS_SETTINGS_OBSERVABILITY', 'observability'),
          ('EFS_SETTINGS_FAULT_HOOKS', 'fault/test hook'))
BEGIN = '    /* BEGIN GENERATED by scripts/gen_settings.py from %s */\n' % DOC
END = '    /* END GENERATED */\n'


def listing(path):
    """{name: (default, role)} from the '| Setting | Default | Role |' table."""
    rows, on = {}, False
    for line in open(path, encoding='utf-8'):
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if cells == ['Setting', 'Default', 'Role']:
            on = True
        elif on and line.startswith('| `'):
            name, default, role = (c.strip('`') for c in cells)
            if role not in ROLES:
                raise SystemExit('gen_settings: %s: role of %s is %r, want %s'
                                 % (DOC, name, role, '/'.join(ROLES)))
            rows[name] = (default, ROLES[role])
        elif on and not line.startswith('|'):
            break
    return rows


def generate(root):
    doc = os.path.join(root, DOC)
    kinds = env_inventory.inventory_kinds(doc)
    rows = listing(doc)
    want = {n for n, k in kinds.items() if k in LISTED}
    got = {n for n in rows if n.startswith('EFS_')}
    if want != got:
        raise SystemExit('gen_settings: %s: listing and inventory disagree: '
                         'no listing row for %s; no inventory row of a listed kind for %s'
                         % (DOC, sorted(want - got), sorted(got - want)))
    groups = [[], [], [n for n in rows if not n.startswith('EFS_')]]
    for n in sorted(want):
        groups[0 if kinds[n] == 'deployment input' else 1].append(n)
    region = ''
    for g in groups:
        cells = ['R("%s", "%s", %s, %s)' % (n, rows[n][0], LISTED.get(kinds.get(n), 'NUM'), rows[n][1])
                 for n in g]
        for i in range(0, len(cells), 2):
            region += '    ' + ' '.join(c + ',' for c in cells[i:i + 2]) + '\n'
    counts = {m: sum(1 for k in kinds.values() if k == kind) for m, kind in COUNTS}
    return region, counts


def render(root):
    """{path: new text} for the two generated files."""
    region, counts = generate(root)
    out = {}
    p = os.path.join(root, 'src/common/settings.c')
    s = open(p, encoding='utf-8').read()
    a, b = s.find(BEGIN), s.find(END)
    if a < 0 or b < a:
        raise SystemExit('gen_settings: %s lacks the BEGIN/END GENERATED markers' % p)
    out[p] = s[:a + len(BEGIN)] + region + s[b:]
    p = os.path.join(root, 'include/efs/settings.h')
    s = open(p, encoding='utf-8').read()
    for macro, n in counts.items():
        s, k = re.subn(r'(#define %s )\d+' % macro, r'\g<1>%d' % n, s)
        if k != 1:
            raise SystemExit('gen_settings: %s has no #define %s' % (p, macro))
    out[p] = s
    return out


def main(argv):
    args = argv[1:]
    root = ROOT
    if args[:1] == ['--root']:
        root, args = os.path.abspath(args[1]), args[2:]
        env_inventory.set_root(root)
    if args not in ([], ['--check']):
        print(__doc__, file=sys.stderr)
        return 2
    new = render(root)
    stale = 0
    for p, text in new.items():
        old = open(p, encoding='utf-8').read()
        if old == text:
            continue
        stale += 1
        if args:
            sys.stdout.writelines(difflib.unified_diff(
                old.splitlines(True), text.splitlines(True), p, p + ' (generated)'))
        else:
            open(p, 'w', encoding='utf-8').write(text)
    if args:
        print('gen_settings: %s' % ('%d files stale; run scripts/gen_settings.py' % stale if stale else 'PASS'))
        return 1 if stale else 0
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
