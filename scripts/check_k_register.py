#!/usr/bin/env python3
"""Check the alpha K register: one file docs/status/k/K<NNN>.md per row is the source.

Usage: python3 scripts/check_k_register.py [CHECKLIST] [--json] [--write]
The row files must cover K1 through the highest number with no gap or duplicate
and a canonical State line. The register table and counts line between the
K-REGISTER markers in the checklist are generated from them (--write rewrites
them; without it a stale block fails). This validates structure, not evidence.
"""
import argparse
from collections import Counter
import json
from pathlib import Path
import re

STATES = ('FIXED', 'VERIFIED', 'VERIFY', 'DECIDED', 'CLOSED', 'OPEN')
COUNT_ORDER = ('FIXED', 'VERIFIED', 'VERIFY', 'CLOSED', 'DECIDED', 'OPEN')
DEFAULT = Path(__file__).resolve().parents[1] / 'docs/status/alpha-1.0-2plus1-checklist.md'
BEGIN = '<!-- K-REGISTER:BEGIN (generated by scripts/check_k_register.py --write) -->'
END = '<!-- K-REGISTER:END -->'
FIELD = re.compile(r'- (State|Blocks alpha|Kind): (.*)')


def read_rows(kdir):
    """Return diagnostics and {number: (title, kind, state, blocks)} from the row files."""
    errors, rows = [], {}
    for path in sorted(kdir.glob('K*.md')):
        m = re.fullmatch(r'K([0-9]{3,})\.md', path.name)
        if not m or path.name != f'K{int(m[1]):03d}.md' or int(m[1]) < 1:
            errors.append(f'{path.name}: not a canonical row file name K<NNN>.md')
            continue
        n = int(m[1])
        lines = path.read_text().splitlines()
        head = re.fullmatch(rf'# K{n}: (.+)', lines[0]) if lines else None
        field = dict(m.groups() for m in map(FIELD.fullmatch, lines[1:8]) if m)
        if not head:
            errors.append(f'{path.name}: first line must be "# K{n}: <title>"')
        elif field.get('State') not in STATES:
            errors.append(f'{path.name}: State must be one of {", ".join(STATES)}')
        elif field.get('Blocks alpha') not in ('yes', 'no', 'unstated'):
            errors.append(f'{path.name}: Blocks alpha must be yes, no or unstated')
        elif 'Kind' not in field:
            errors.append(f'{path.name}: missing Kind line')
        else:
            rows[n] = (head[1], field['Kind'], field['State'], field['Blocks alpha'])
    missing = set(range(1, max(rows, default=0) + 1)) - set(rows)
    if missing and not errors:
        errors.append('missing ' + ', '.join(f'K{k}' for k in sorted(missing)))
    if not rows and not errors:
        errors.append(f'no K row files in {kdir}')
    return errors, rows


def cell(s):
    return s.replace('|', '/')  # a pipe would change the cell count


def generate(rows):
    counts = Counter(r[2] for r in rows.values())
    out = ['| ID | Title | Kind | State | Blocks alpha | Row |', '| --- | --- | --- | --- | --- | --- |']
    for n, (title, kind, state, blocks) in sorted(rows.items()):
        out.append(f'| K{n} | {cell(title)} | {cell(kind)} | {state} | {blocks} | [K{n:03d}](k/K{n:03d}.md) |')
    out += ['', 'Current counts: ' + ' / '.join(f'{counts[s]} {s}' for s in COUNT_ORDER) + f' ({len(rows)} rows).']
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('checklist', nargs='?', type=Path, default=DEFAULT)
    parser.add_argument('--json', action='store_true', help='print states/counts and diagnostics as JSON')
    parser.add_argument('--write', action='store_true', help='rewrite the generated block in the checklist')
    args = parser.parse_args()
    try:
        text = args.checklist.read_text()
    except OSError as exc:
        parser.exit(1, f'K register: {exc}\n')
    errors, rows = read_rows(args.checklist.parent / 'k')
    counts = Counter(r[2] for r in rows.values())
    if not errors:
        block = f'{BEGIN}\n{generate(rows)}\n{END}'
        found = re.search(re.escape(BEGIN) + '.*?' + re.escape(END), text, re.S)
        if not found or text.count(BEGIN) != 1 or text.count(END) != 1:
            errors.append('checklist needs exactly one K-REGISTER marker pair')
        elif found[0] != block:
            if args.write:
                args.checklist.write_text(text[:found.start()] + block + text[found.end():])
            else:
                errors.append('generated register is stale: run scripts/check_k_register.py --write')
    result = {'counts': {s: counts[s] for s in STATES},
              'rows': {f'K{k}': v[2] for k, v in sorted(rows.items())},
              'errors': errors}
    if args.json:
        print(json.dumps(result, indent=2))
    elif errors:
        print('\n'.join('FAIL K register: ' + e for e in errors))
    else:
        print('PASS K register: ' + str(len(rows)) + ' rows; ' + ', '.join(f'{s}={counts[s]}' for s in STATES))
    return bool(errors)


if __name__ == '__main__':
    raise SystemExit(main())
