#!/usr/bin/env python3
"""gen_diagnostics.py [--check]: write docs/how-it-works/diagnostics.md.

Maps every diagnostic key (a leading `word-word` token of a string literal
passed to fprintf(stderr, ...) or efs_telemetry_log(level, ...)) to its file,
enclosing function and component tag, and every EFS_ERR_* code of
include/efs/common.h to its number and meaning. --check exits 1 when the page
on disk differs. Deterministic: sorted by byte value, no timestamps, no git.
"""
import importlib.util, re, sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
page = root / 'docs/how-it-works/diagnostics.md'
spec = importlib.util.spec_from_file_location('tests_for', root / 'scripts/tests_for.py')
tf = importlib.util.module_from_spec(spec)
spec.loader.exec_module(tf)

CALL = re.compile(r'\b(fprintf\s*\(\s*stderr|efs_telemetry_log\s*\(\s*[^,;"]*)\s*,\s*"((?:[^"\\]|\\.)*)"')
KEY = re.compile(r'^([a-z][a-z0-9]*(?:-[a-z0-9]+)+)(?=[ :])')
FUNC = re.compile(r'^[A-Za-z_][^;=#]*?\b([A-Za-z_]\w*)\s*\(')
NOT_FUNC = {'if', 'for', 'while', 'switch', 'return', 'sizeof', 'typedef', 'else', 'do'}


def strip_comments(s):
    """Blank comments, keep newlines and string literals (offsets stay valid)."""
    def blank(m):
        t = m.group(0)
        return t if t[0] in '"\'' else re.sub(r'[^\n]', ' ', t)
    return re.sub(r'"(?:[^"\\\n]|\\.)*"|\'(?:[^\'\\\n]|\\.)*\'|/\*.*?\*/|//[^\n]*', blank, s, flags=re.S)


def tag(rel):
    """Component tag of a source path: src/<dir>/<name>.c -> dir/name,
    src/<dir>/<sub>/<name>.c -> dir/sub.name (the budgets.tsv spelling);
    include/efs/<name>.h -> the src component of that name, else include/<name>."""
    p = Path(rel)
    if p.parts[0] == 'include':
        for d in sorted(x.name for x in (root / 'src').iterdir() if x.is_dir()):
            if tf.component_exists(d + '/' + p.stem, root / 'src'):
                return d + '/' + p.stem
        return 'include/' + p.stem
    parts = p.parts[1:]
    if len(parts) == 2:
        return parts[0] + '/' + p.stem
    return parts[0] + '/' + parts[1] + '.' + p.stem


def functions(lines):
    """[(line index, name)] of column-0 definitions: a declarator line whose
    parameter list is followed by `{` before any `;` (this or a later line)."""
    out = []
    for i, ln in enumerate(lines):
        if not ln or ln[0] in ' \t#}/*{)' or ln.startswith(('typedef', 'struct ', 'enum ', 'union ')) and '(' not in ln:
            continue
        m = FUNC.match(ln)
        if not m or m.group(1) in NOT_FUNC:
            continue
        j, depth, seen = i, 0, False
        while j < len(lines) and j < i + 40:
            for ch in lines[j]:
                if ch == '(':
                    depth += 1; seen = True
                elif ch == ')':
                    depth -= 1
                elif depth == 0 and seen and ch == ';':
                    j = None; break
                elif depth == 0 and seen and ch == '{':
                    out.append((i, m.group(1))); j = None; break
            if j is None:
                break
            j += 1
    return out


def scan():
    keys, nokey = {}, 0
    for base in ('src', 'include'):
        for f in sorted((root / base).rglob('*')):
            if f.suffix not in ('.c', '.h') or not f.is_file():
                continue
            rel = f.relative_to(root).as_posix()
            text = strip_comments(f.read_text(errors='replace'))
            lines = text.split('\n')
            funcs = functions(lines)
            for m in CALL.finditer(text):
                line = text.count('\n', 0, m.start())
                if not m.group(1).startswith('fprintf') and 'telemetry' not in m.group(1):
                    continue
                k = KEY.match(m.group(2))
                if not k:
                    if m.group(1).startswith('fprintf'):
                        nokey += 1
                    continue
                fn = '?'
                for i, name in funcs:
                    if i <= line:
                        fn = name
                    else:
                        break
                keys.setdefault((k.group(1), rel, fn), tag(rel))
    return keys, nokey


def render():
    keys, nokey = scan()
    errs = []
    for ln in (root / 'include/efs/common.h').read_text().splitlines():
        m = re.match(r'#define\s+(EFS_ERR_\w+)\s+(-\d+)\s*(?:/\*\s*(.*?)\s*\*/)?\s*$', ln)
        if m:
            errs.append((int(m.group(2)), m.group(1), m.group(3) or ''))
    errs.sort(reverse=True)
    nkeys = len({k for k, _, _ in keys})
    out = ['<!-- Generated by `python3 scripts/gen_diagnostics.py`; do not edit. -->',
           '# Diagnostics index',
           '',
           'Generated page: any source change that adds, renames or moves a diagnostic key '
           'must regenerate it with `python3 scripts/gen_diagnostics.py` (`make docs-check` '
           'runs it with `--check` and fails on a stale page).',
           '',
           'Look a log key or `rc` up here, then `graphify explain <Component>`. '
           'Scanned: every `.c` and `.h` under `src/` and `include/`; the calls '
           '`fprintf(stderr, "...")` and `efs_telemetry_log(level, "...")` (the other `*log*` '
           'functions take no literal key or are not diagnostics). A key is the leading '
           '`word-word` token of the literal, followed by a space or `:`.',
           '',
           'Found: %d diagnostic keys in %d (key, function) rows, %d error codes; '
           '%d `fprintf(stderr` calls carry no key and are not listed.' % (nkeys, len(keys), len(errs), nokey),
           '',
           '## Error codes',
           '',
           '| rc | Name | Meaning |', '|---|---|---|']
    out += ['| %d | `%s` | %s |' % (n, name, c) for n, name, c in errs]
    out += ['', '## Diagnostic keys', '', '| Key | File | Function | Component |', '|---|---|---|---|']
    out += ['| `%s` | `%s` | `%s` | `%s` |' % (k, f, fn, t) for (k, f, fn), t in sorted(keys.items())]
    return '\n'.join(out) + '\n'


def main(argv):
    if argv not in ([], ['--check']):
        sys.exit('usage: gen_diagnostics.py [--check]')
    new = render()
    if argv:
        if not page.exists() or page.read_text() != new:
            print('gen_diagnostics: %s is stale; run python3 scripts/gen_diagnostics.py' % page.relative_to(root), file=sys.stderr)
            sys.exit(1)
        return
    page.write_text(new)


if __name__ == '__main__':
    main(sys.argv[1:])
