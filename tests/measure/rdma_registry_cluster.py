#!/usr/bin/env python3
"""Task AI private single-host IOR control, never an existing cluster.

Run on the assigned Linux RDMA host. Fresh output only; failure preserves stores
and logs. No lock optimization is selected by this driver. The diagnostic build
must be a separate source tree generated by rdma_registry_probe.py. IOR easy uses
file-per-process 1 MiB transfers, 64 MiB/rank; hard uses a shared file, 47008-byte
transfers, 128 segments/rank. These bounded geometries are not full IO500 scores.
Three repeats across TCP/native RDMA/probe RDMA and 1/8/32 local MPI ranks.
Use --smoke for only native RDMA/one rank, before starting the full matrix.
"""
import argparse
import concurrent.futures
import hashlib
import json
import os
from pathlib import Path
import signal
import subprocess
import sys
import threading
import time
import traceback


def save(path, value):
    tmp = path.with_suffix(path.suffix + '.tmp')
    tmp.write_text(json.dumps(value, indent=2) + '\n')
    tmp.replace(path)


def foreign_work(private):
    """Inspect argv/exe, exclude this driver's ancestry; uncertainty refuses."""
    found = []
    for p in Path('/proc').iterdir():
        if not p.name.isdigit():
            continue
        try:
            raw = (p / 'cmdline').read_bytes().split(b'\0')
            argv = [x.decode(errors='replace') for x in raw if x]
            if not argv:
                continue
            exe = Path(argv[0]).name
            relevant = (exe in ('efsd', 'efs-fuse', 'ior', 'mdtest', 'efs-bench') or
                        exe.startswith('test_') or
                        any(Path(a).name.startswith(('test_', 'taskH', 'taskI')) for a in argv[1:3]))
            if relevant and not any(str(private) in a for a in argv):
                found.append(dict(pid=int(p.name), argv=argv[:6]))
        except FileNotFoundError:
            continue
        except PermissionError:
            # cmdline is normally world-readable on this host. Hidden processes
            # must not be interpreted as an idle machine.
            found.append(dict(pid=int(p.name), unknown=True))
    return found


def run(cmd, log, env, timeout=600):
    start = time.monotonic()
    with log.open('x') as f:
        f.write(json.dumps(dict(argv=list(map(str, cmd)))) + '\n'); f.flush()
        p = subprocess.run(list(map(str, cmd)), stdout=f, stderr=subprocess.STDOUT,
                           env=env, timeout=timeout)
    result = dict(command=list(map(str, cmd)), rc=p.returncode,
                  elapsed_s=time.monotonic()-start)
    if p.returncode:
        raise RuntimeError(f'{log}: exit {p.returncode}')
    return result


def fixed_rewrites(mount, streams, seconds):
    """20 fsynced 4-KiB rewrites/s/stream, 8 fixed files each; no timing retries."""
    root = mount / 'fixed-rewrites'; root.mkdir()
    barrier = threading.Barrier(streams)
    def worker(s):
        paths = [root / f'{s}-{i}' for i in range(8)]
        for p in paths:
            p.write_bytes(bytes(4096))
        expected = {}; lat = []; barrier.wait(); start = time.monotonic()
        for n in range(int(seconds*20)):
            due = start+n/20
            if due > time.monotonic():
                time.sleep(due-time.monotonic())
            p = paths[n % len(paths)]
            data = hashlib.shake_256(f'{s}:{n}'.encode()).digest(4096)
            t = time.monotonic()
            with p.open('r+b', buffering=0) as f:
                assert f.write(data) == len(data)
                os.fsync(f.fileno())
            lat.append(time.monotonic()-t); expected[p] = data
        for p, data in expected.items():
            if p.read_bytes() != data:
                raise RuntimeError(f'acknowledged final payload mismatch: {p}')
        return dict(stream=s, operations=len(lat), elapsed_s=time.monotonic()-start,
                    fsync_syscall_s=lat)
    with concurrent.futures.ThreadPoolExecutor(max_workers=streams) as pool:
        return list(pool.map(worker, range(streams)))


def cell(args, k, out, label, streams, repeat, source, transport):
    path = out / f'{label}-{streams}-r{repeat}'; path.mkdir()
    env = {a:b for a,b in os.environ.items() if not a.startswith('EFS_')}
    env.update(EFS_TRANSPORT=transport, EFS_RDMA_DEV='mlx5_0', EFS_RAFT_OBS='1',
               TMPDIR=str(args.private / 'tmp'))
    k.EFSD, k.MGMT, k.FUSE = (source / n for n in ('efsd','efs-mgmt','efs-fuse'))
    c = k.Cluster(path, 'cluster', [1,2,3], env)
    result = dict(source=str(source), transport=transport, streams=streams,
                  repeat=repeat, verdict='RUNNING', quota='16G/node', direct_io=True)
    save(path/'result.json', result)
    mount = None; observer_stop = threading.Event(); samples = []; overlaps = []
    def observe():
        while not observer_stop.wait(0.1):
            t = time.monotonic()
            try:
                os.stat(mount.path/'stat-target')
                samples.append(time.monotonic()-t)
                if len(samples) % 20 == 0:
                    overlaps.extend(foreign_work(args.private))
            except Exception as e:
                overlaps.append(dict(observer_error=str(e))); return
    observer = None
    try:
        for i in (1,2,3):
            c.start(i, join=None if i==1 else 1, quota='16G', args=('--writers','8','--direct-io'))
        for i in (1,2,3):
            c.wait_log(i, 'raft-host: formed: 3 members', timeout=90)
        result['members'] = c.wait_members([1,2,3], 3)
        mount = k.Mount(c, 1, 'mnt')
        (mount.path/'stat-target').write_bytes(b'AI\n')
        observer = threading.Thread(target=observe); observer.start()
        result['rewrites'] = fixed_rewrites(mount.path, streams, 5 if args.smoke else 30)
        result['ior'] = []
        for geometry in ('easy','hard'):
            target = mount.path/f'ior-{geometry}'
            base = [args.mpi, '--oversubscribe', '--bind-to','none', '-np', str(streams),
                    args.ior, '-a','POSIX','--dataPacketType=timestamp', '-C','-Q','1',
                    '-g','-G','271828','-k','-e']
            base += ['-F','-t','1m','-b','64m'] if geometry=='easy' else [
                '-t','47008','-b','47008','-s','128']
            for mode in ('write','verify'):
                cmd = base + (['-w'] if mode=='write' else ['-r','-R']) + ['-o',target]
                row = run(cmd, path/f'ior-{geometry}-{mode}.log', env, timeout=1800)
                row.update(geometry=geometry, mode=mode); result['ior'].append(row)
        observer_stop.set(); observer.join()
        result.update(stat_syscall_s=samples, observed_foreign_work=overlaps,
                      stat_limit='FUSE attribute cache applies; syscall latency, not per-RPC proof')
        if overlaps:
            raise RuntimeError('shared workload or observation uncertainty: timing unqualified')
        result['stop'] = run(['bash',source/'scripts/client.sh','stop',mount.path],
                             path/'mount-stop.log', env, timeout=660)
        mount.p.wait(timeout=30)
        if os.path.ismount(mount.path) or mount.p.returncode != 0:
            raise RuntimeError('mount stop did not finish cleanly')
        for i,p in c.procs.items():
            p.send_signal(signal.SIGTERM)
        exits = {str(i):p.wait(timeout=90) for i,p in c.procs.items()}
        result['daemon_exits'] = exits
        if any(exits.values()):
            raise RuntimeError(f'unclean daemon exits: {exits}')
        result['verdict'] = 'PASS_SCOPED'
    except BaseException:
        result.update(verdict='FAIL', error=traceback.format_exc(),
                      live_processes={str(i):p.pid for i,p in c.procs.items() if p.poll() is None},
                      mount_pid=mount.p.pid if mount else None)
        # Preserve failed mounts/stores for diagnosis; never lazy detach or kill.
        raise
    finally:
        observer_stop.set()
        if observer: observer.join(timeout=5)
        save(path/'result.json', result)
        for h in c.held: h.close()
    return result


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('private', type=Path); p.add_argument('out', type=Path)
    p.add_argument('--ior', type=Path, required=True); p.add_argument('--mpi', type=Path, required=True)
    p.add_argument('--smoke', action='store_true')
    a = p.parse_args(); a.private = a.private.resolve(); a.out = a.out.resolve()
    if a.out.exists() or not str(a.out).startswith(str(a.private)+'/'):
        p.error('fresh output strictly below the private tree required')
    found = foreign_work(a.private)
    if found: raise RuntimeError(f'host not quiet: {found}')
    a.out.mkdir()
    sys.path.insert(0, str(a.private/'native/tests'))
    import k33_daemons as k
    matrix = [('native-rdma','native','rdma')] if a.smoke else [
        ('native-tcp','native','tcp'), ('native-rdma','native','rdma'), ('probe-rdma','probe','rdma')]
    state = dict(verdict='RUNNING', cells=[]); save(a.out/'state.json',state)
    try:
        for repeat in range(1,2 if a.smoke else 4):
            for streams in ((1,) if a.smoke else (1,8,32)):
                # Alternate native transport order by repeat; probe always separate.
                ordered = matrix if repeat % 2 else [matrix[1],matrix[0],matrix[2]]
                for label,source,transport in ordered:
                    state['current'] = f'{label}-{streams}-r{repeat}'; save(a.out/'state.json',state)
                    result = cell(a,k,a.out,label,streams,repeat,a.private/source,transport)
                    state['cells'].append(dict(name=state['current'],verdict=result['verdict']))
                    save(a.out/'state.json',state)
        state['verdict'] = 'PASS_SCOPED'
    except BaseException:
        state.update(verdict='FAIL',error=traceback.format_exc()); raise
    finally: save(a.out/'state.json',state)


if __name__ == '__main__': main()
