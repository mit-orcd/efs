#!/usr/bin/env python3
"""Generate the C command-source literal; reading it never queries EFS."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent
source = (root / 'command.py').read_text()
(root / 'source.h').write_text('/* Generated by commands/embed.py; edit command.py. */\n'
                              'static const char efs_command_source[] =\n' +
                              '\n'.join(json.dumps(line) for line in source.splitlines(keepends=True)) + ';\n')
